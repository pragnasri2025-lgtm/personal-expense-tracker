-- Personal Expense Tracker Management System
-- Relational Database Schema (Compatible with MySQL 8+ and SQLite)

CREATE TABLE IF NOT EXISTS USER (
  User_ID INT AUTO_INCREMENT PRIMARY KEY,
  Name VARCHAR(120) NOT NULL,
  Email VARCHAR(190) NOT NULL UNIQUE,
  Password_Hash VARCHAR(255) NOT NULL,
  Currency VARCHAR(10) NOT NULL DEFAULT 'USD',
  Created_At TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS INCOME (
  Income_ID INT AUTO_INCREMENT PRIMARY KEY,
  User_ID INT NOT NULL,
  Amount DECIMAL(12, 2) NOT NULL,
  Category VARCHAR(60) NOT NULL,
  Date DATE NOT NULL,
  Description VARCHAR(255) NOT NULL DEFAULT '',
  Created_At TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_income_user FOREIGN KEY (User_ID) REFERENCES USER(User_ID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS EXPENSE (
  Expense_ID INT AUTO_INCREMENT PRIMARY KEY,
  User_ID INT NOT NULL,
  Amount DECIMAL(12, 2) NOT NULL,
  Category VARCHAR(60) NOT NULL,
  Payment_Method VARCHAR(60) NOT NULL,
  Date DATE NOT NULL,
  Description VARCHAR(255) NOT NULL DEFAULT '',
  Created_At TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_expense_user FOREIGN KEY (User_ID) REFERENCES USER(User_ID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS BUDGET (
  Budget_ID INT AUTO_INCREMENT PRIMARY KEY,
  User_ID INT NOT NULL,
  Category VARCHAR(60) NOT NULL,
  Month TINYINT NOT NULL,
  Year SMALLINT NOT NULL,
  Budget_Amount DECIMAL(12, 2) NOT NULL,
  Created_At TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_user_budget_period (User_ID, Category, Month, Year),
  CONSTRAINT fk_budget_user FOREIGN KEY (User_ID) REFERENCES USER(User_ID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS EXPENSE_CATEGORY (
  Category_ID INT AUTO_INCREMENT PRIMARY KEY,
  User_ID INT NOT NULL,
  Name VARCHAR(60) NOT NULL,
  Is_Default TINYINT(1) NOT NULL DEFAULT 0,
  UNIQUE KEY uq_user_category (User_ID, Name),
  CONSTRAINT fk_category_user FOREIGN KEY (User_ID) REFERENCES USER(User_ID) ON DELETE CASCADE
);
